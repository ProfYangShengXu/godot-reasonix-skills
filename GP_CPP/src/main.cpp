// =====================================================
// 文件名: main.cpp
// 功能: 客户端应用程序主入口
// 说明: 创建Qt应用程序并显示主窗口
// =====================================================

#include "ui/mainwindow.h"   // 主窗口类
#include <QApplication>       // Qt应用程序类

// =====================================================
// 主函数：应用程序的入口点
// =====================================================
// @param argc: 命令行参数数量
// @param argv: 命令行参数数组
// @return: 应用程序退出码（0表示正常退出）
int main(int argc, char *argv[])
{
    // 创建Qt应用程序对象
    // QApplication管理整个应用程序的生命周期和事件循环
    QApplication app(argc, argv);
    
    // 创建主窗口实例
    // MainWindow是运动评估系统的主界面
    MainWindow window;
    
    // 显示主窗口
    // show()是非阻塞调用，窗口会显示但不会停止程序执行
    window.show();
    
    // 进入Qt事件循环
    // exec()会持续运行直到应用程序退出（如关闭所有窗口）
    // 返回值是程序退出码
    return app.exec();
}
